var texto : String;
texto = "vermelho"

switch texto{

    case "vermelho":
        print("PARE!")
    case "amarelo":
        print("ATENCAO!")
    case "verde":
        print("Siga!")
    case "piscando":
        print("Pare, e siga em frente!")

    default:
        print("Semáforo desligado!")
}